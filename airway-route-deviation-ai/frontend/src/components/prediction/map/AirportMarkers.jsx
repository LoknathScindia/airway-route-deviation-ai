import { Marker, Popup } from "react-leaflet";

function isValidAirport(airport) {
  return (
    airport &&
    airport.latitude !== undefined &&
    airport.longitude !== undefined &&
    airport.latitude !== null &&
    airport.longitude !== null &&
    !isNaN(Number(airport.latitude)) &&
    !isNaN(Number(airport.longitude))
  );
}

function AirportMarkers({
  departureAirport,
  destinationAirport,
  alternateRoute,
}) {
  const alternateAirports =
    alternateRoute?.success && Array.isArray(alternateRoute.route)
      ? alternateRoute.route.filter(
          (airport) =>
            isValidAirport(airport) &&
            airport.icao !== departureAirport?.icao &&
            airport.icao !== destinationAirport?.icao
        )
      : [];

  return (
    <>
      {/* Departure Airport */}
      {isValidAirport(departureAirport) && (
        <Marker
          position={[
            Number(departureAirport.latitude),
            Number(departureAirport.longitude),
          ]}
        >
          <Popup>
            <div className="min-w-[180px]">
              <h3 className="font-bold text-blue-700">
                🛫 Departure Airport
              </h3>

              <p className="mt-2 font-semibold">
                {departureAirport.name}
              </p>

              <p>ICAO: {departureAirport.icao}</p>
            </div>
          </Popup>
        </Marker>
      )}

      {/* Destination Airport */}
      {isValidAirport(destinationAirport) && (
        <Marker
          position={[
            Number(destinationAirport.latitude),
            Number(destinationAirport.longitude),
          ]}
        >
          <Popup>
            <div className="min-w-[180px]">
              <h3 className="font-bold text-red-700">
                🛬 Destination Airport
              </h3>

              <p className="mt-2 font-semibold">
                {destinationAirport.name}
              </p>

              <p>ICAO: {destinationAirport.icao}</p>
            </div>
          </Popup>
        </Marker>
      )}

      {/* Alternate Route Airports */}
      {alternateAirports.map((airport, index) => (
        <Marker
          key={`${airport.icao}-${index}`}
          position={[
            Number(airport.latitude),
            Number(airport.longitude),
          ]}
        >
          <Popup>
            <div className="min-w-[180px]">
              <h3 className="font-bold text-green-700">
                ✈ AI Alternate Route
              </h3>

              <p className="mt-2 font-semibold">
                {airport.name}
              </p>

              <p>ICAO: {airport.icao}</p>

              <p className="mt-2 text-sm text-slate-600">
                Recommended waypoint generated by the AI routing engine.
              </p>
            </div>
          </Popup>
        </Marker>
      ))}
    </>
  );
}

export default AirportMarkers;