function FlightStatus({ result }) {
  if (!result) return null;

  const confidence = (result.confidence * 100).toFixed(2);

  const statusColor =
    result.prediction === 1
      ? "bg-red-100 text-red-700"
      : "bg-green-100 text-green-700";

  const riskColor =
    result.risk_level === "High"
      ? "bg-red-100 text-red-700"
      : result.risk_level === "Medium"
      ? "bg-yellow-100 text-yellow-700"
      : "bg-green-100 text-green-700";

  return (
    <div className="mt-6 rounded-2xl bg-white p-6 shadow-lg">

      <div className="mb-6 border-b pb-4">
        <h2 className="text-2xl font-bold text-slate-800">
          Flight Operations Status
        </h2>

        <p className="mt-1 text-slate-500">
          Live operational summary generated by the Flight AI engine.
        </p>
      </div>

      <div className="grid gap-5 md:grid-cols-2">

        <div className="rounded-xl border p-5">
          <p className="text-sm text-slate-500">
            Flight Status
          </p>

          <span
            className={`mt-3 inline-block rounded-full px-4 py-2 font-semibold ${statusColor}`}
          >
            {result.status}
          </span>
        </div>

        <div className="rounded-xl border p-5">
          <p className="text-sm text-slate-500">
            Risk Level
          </p>

          <span
            className={`mt-3 inline-block rounded-full px-4 py-2 font-semibold ${riskColor}`}
          >
            {result.risk_level}
          </span>
        </div>

        <div className="rounded-xl border p-5">
          <p className="text-sm text-slate-500">
            Model Confidence
          </p>

          <h3 className="mt-2 text-2xl font-bold">
            {confidence}%
          </h3>
        </div>

        <div className="rounded-xl border p-5">
          <p className="text-sm text-slate-500">
            Recommended Action
          </p>

          <p className="mt-2 font-medium text-slate-700">
            {result.recommendation}
          </p>
        </div>

      </div>

      <div className="mt-6 rounded-xl bg-slate-50 p-5">

        <h3 className="mb-3 text-lg font-bold text-slate-800">
          Operational Summary
        </h3>

        <ul className="space-y-2 text-slate-700">

          <li>
            ✓ Prediction generated successfully.
          </li>

          <li>
            ✓ AI confidence: <strong>{confidence}%</strong>
          </li>

          <li>
            ✓ Risk assessment:
            <strong> {result.risk_level}</strong>
          </li>

          <li>
            ✓ Estimated fuel saving:
            <strong> {result.fuel_saving} kg</strong>
          </li>

          <li>
            ✓ Estimated CO₂ reduction:
            <strong> {result.co2_reduction} kg</strong>
          </li>

        </ul>

      </div>

    </div>
  );
}

export default FlightStatus;